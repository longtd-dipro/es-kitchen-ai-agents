/* CSV を作って保存する（UTF-8・BOM 付き。本番は Shift_JIS に変換して出す） */

const q = (v: unknown) => { const s = String(v ?? ''); return /[",\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s; };

export function csvText(head: string[], rows: (string | number)[][]) {
  return '﻿' + [head, ...rows].map((r) => r.map(q).join(',')).join('\r\n') + '\r\n';
}

export function downloadCsv(file: string, head: string[], rows: (string | number)[][]) {
  const blob = new Blob([csvText(head, rows)], { type: 'text/csv;charset=utf-8' });
  const url = URL.createObjectURL(blob), a = document.createElement('a');
  a.href = url; a.download = file;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

/** ファイルを選んで中身（行数）を読む */
export function pickCsv(): Promise<{ name: string; lines: number } | null> {
  return new Promise((resolve) => {
    const inp = document.createElement('input');
    inp.type = 'file'; inp.accept = '.csv,text/csv';
    inp.onchange = () => {
      const f = inp.files?.[0];
      if (!f) return resolve(null);
      const r = new FileReader();
      r.onload = () => resolve({ name: f.name, lines: Math.max(String(r.result).split(/\r?\n/).filter((l) => l.trim()).length - 1, 0) });
      r.readAsText(f);
    };
    inp.click();
  });
}

