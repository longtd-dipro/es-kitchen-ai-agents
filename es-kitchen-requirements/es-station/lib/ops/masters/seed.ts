/*
 * マスタの見本のうち、共通データ（dm.master.*）にない値。一覧の行（seedRows.ts）・機種の詳細の主な項目（deviceFill）・
 * プランの価格の世代と標準貸出設備（PLAN_DB）。名前・料金・状態などは共通データが正（fromDomain.ts で重ねる）。
 * 元のデモは、行に data-fill がない機種も詳細を見本（RF000001）のまま出していた。ここでは一覧の行の値
 * （機種名・機種区分・メーカー・月額料金・最低利用期間・公開ステータス・有効状態）を詳細にも当てる。
 */

/** 機種：一覧の行から詳細の主な項目を作る */
export function deviceFill(r: SeedRow): Fill {
  const c = r.row, kind = c.kind;
  const maker = { 冷蔵庫: '冷蔵庫／冷凍庫メーカー', 冷凍庫: '冷蔵庫／冷凍庫メーカー', 自販機: '自販機メーカー', 電子レンジ: '電子レンジメーカー', ホットウォーマー: 'ホットウォーマーメーカー' }[kind];
  const f: Fill = {
    機種ID: r.id, 機種名: r.name, 機種区分: kind, 公開ステータス: c.pubst, '月額料金（税抜き）': c.fee.replace(/^¥|円$/g, ''), 最低利用期間: c.term.replace(/ヶ月$/, '').replace(/^—$/, ''),
    '@機種ID': r.id, '@機種名': r.name, '@機種区分': kind, '@メーカー': c.maker, '@月額料金（税抜き）': c.fee, '@最低利用期間': c.term, '@公開ステータス': c.pubst, '@貸出中': c.n,
  };
  if (['有効', '無効'].includes(c.status)) f['有効状態'] = c.status;
  if (maker && c.maker !== '—') f[maker] = c.maker;
  return { ...f, ...(r.fill ?? {}) };
}

